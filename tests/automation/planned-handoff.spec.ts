// PLANNED-HANDOFF ACCEPTANCE (post-planning throughput gap).
//
// Law under test: an unplanned wave-eligible package takes the planning-ONLY
// bootstrap (zero implementation nodes); when its planning truth becomes
// deterministically complete that execution TERMINATES, and the supervisor
// performs a first-class handoff — verify at the run worktree, promote the
// scoped planning artifacts to main, and IMMEDIATELY reselect the SAME
// still-RUNNING package into `foresift-sharded-wave`. Crash-safe,
// duplicate-safe, adoption-safe, generation-aware; legacy topologies
// untouched.
//
// Layers:
//   1. Structural — the bootstrap DAG cannot dispatch an implementation
//      provider because no such node exists.
//   2. CLI flows — the REAL supervisor subprocess against hermetic git
//      fixtures + a scripted archon stub, covering launch demotion (A),
//      direct wave admission (E), the completed-bootstrap handoff
//      (B/C/D/G/H/I), legacy preservation (F), and artifact preservation
//      (J).
