const PKG = 'pkg-alpha';
const BOOTSTRAP_WF = 'foresift-package-planning-bootstrap';
const WAVE_WF = 'foresift-sharded-wave';
const OPTIMIZED_WF = 'foresift-work-package-optimized';

// ── structural: the planning bootstrap cannot implement ─────────────────────
describe('structural: planning-bootstrap DAG carries zero implementation nodes', () => {
  const yaml = readFileSync(BOOTSTRAP_YAML, 'utf8');
  const waveYaml = readFileSync(WAVE_YAML, 'utf8');

  it('has no implementation/gate/landing provider commands (B: zero impl calls by construction)', () => {
    for (const forbidden of [
      'foresift-wp-implement',
      'foresift-wp-gate',
      'package-full-gate',
      'package-create-pr',
      'package-final-land',
    ]) {
      expect(yaml).not.toContain(forbidden);
    }
  });

  it('is the optimized Phases 0A–1 verbatim plus ONE terminal handoff node', () => {
    for (const required of [
      'adopt-generation-branch.mjs',
      'preflight.mjs',
      'package-plan-complete.mjs',
      'command: foresift-wp-plan',
      'none_failed_min_one_success',
      'PLANNING_BOOTSTRAP_COMPLETE',
    ]) {
      expect(yaml).toContain(required);
    }
    // The terminal handoff node is the LAST node and nothing depends on a
    // phase-2 router: no impl-status anywhere.
    expect(yaml).not.toContain('impl-status');
  });

  it('the wave DAG pins its integration base only AFTER branch adoption', () => {
    const adoptionIdx = waveYaml.indexOf('- id: branch-adoption');
    const prepIdx = waveYaml.indexOf('- id: prep');
    const basePinIdx = waveYaml.indexOf('BASE="$(git rev-parse HEAD)"');
    expect(adoptionIdx).toBeGreaterThan(-1);
    expect(prepIdx).toBeGreaterThan(adoptionIdx);
    expect(basePinIdx).toBeGreaterThan(prepIdx);
    expect(waveYaml).toContain('wave-branch-adoption.mjs');
  });
});

